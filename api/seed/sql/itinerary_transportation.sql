CREATE TABLE IF NOT EXISTS ItineraryTransportation
(  TRANSPORTATION        VARCHAR(64) NOT NULL,
   OLD_LIKELIHOOD        INTEGER,
   NEW_LIKELIHOOD        INTEGER,
   ADDED_AS_ATTRACTION   BOOL        NOT NULL DEFAULT 0,
   START_TIME            TEXT,
   END_TIME              TEXT,
   ROUTE                 VARCHAR(64),
   PRIMARY KEY ( TRANSPORTATION ),
   FOREIGN KEY ( TRANSPORTATION ) REFERENCES Transportation(NAME) );
