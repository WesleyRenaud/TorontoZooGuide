CREATE TABLE IF NOT EXISTS RestaurantStatus
(  RESTAURANT         VARCHAR(64) NOT NULL,
   IS_CLOSED          BOOL        NOT NULL DEFAULT 0,
   CLOSED_MESSAGE     TEXT,
   CLOSED_START       DATE,
   CLOSED_END         DATE,
   CLOSED_FOR_SEASON  BOOL        NOT NULL DEFAULT 0,
   PRIMARY KEY (RESTAURANT),
   FOREIGN KEY (RESTAURANT) REFERENCES Restaurant(NAME) );
