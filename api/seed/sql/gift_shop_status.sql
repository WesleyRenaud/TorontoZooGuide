CREATE TABLE IF NOT EXISTS GiftShopStatus
(  GIFT_SHOP          VARCHAR(64) NOT NULL,
   IS_CLOSED          BOOL        NOT NULL DEFAULT 0,
   CLOSED_MESSAGE     TEXT,
   CLOSED_START       DATE,
   CLOSED_END         DATE,
   CLOSED_FOR_SEASON  BOOL        NOT NULL DEFAULT 0,
   PRIMARY KEY (GIFT_SHOP),
   FOREIGN KEY (GIFT_SHOP) REFERENCES GiftShop(NAME) );
