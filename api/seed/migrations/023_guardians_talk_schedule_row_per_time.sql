   SELECT
      TALK_NAME,
      LOCATION,
      SCHEDULE_START_DATE,
      SCHEDULE_END_DATE,
      0 AS MONDAY,
      0 AS TUESDAY,
      0 AS WEDNESDAY,
      1 AS THURSDAY,
      0 AS FRIDAY,
      0 AS SATURDAY,
      0 AS SUNDAY,
      THURSDAY_TIME AS TALK_TIME,
      SCHEDULE_MESSAGE
   FROM GuardiansTalkSchedule
   WHERE THURSDAY_TIME IS NOT NULL
      AND TRIM( THURSDAY_TIME ) != ''

   UNION ALL

   SELECT
      TALK_NAME,
      LOCATION,
      SCHEDULE_START_DATE,
      SCHEDULE_END_DATE,
      0 AS MONDAY,
      0 AS TUESDAY,
      0 AS WEDNESDAY,
      0 AS THURSDAY,
      1 AS FRIDAY,
      0 AS SATURDAY,
      0 AS SUNDAY,
      FRIDAY_TIME AS TALK_TIME,
      SCHEDULE_MESSAGE
   FROM GuardiansTalkSchedule
   WHERE FRIDAY_TIME IS NOT NULL
      AND TRIM( FRIDAY_TIME ) != ''

   UNION ALL

   SELECT
      TALK_NAME,
      LOCATION,
      SCHEDULE_START_DATE,
      SCHEDULE_END_DATE,
      0 AS MONDAY,
      0 AS TUESDAY,
      0 AS WEDNESDAY,
      0 AS THURSDAY,
      0 AS FRIDAY,
      1 AS SATURDAY,
      0 AS SUNDAY,
      SATURDAY_TIME AS TALK_TIME,
      SCHEDULE_MESSAGE
   FROM GuardiansTalkSchedule
   WHERE SATURDAY_TIME IS NOT NULL
      AND TRIM( SATURDAY_TIME ) != ''

   UNION ALL

   SELECT
      TALK_NAME,
      LOCATION,
      SCHEDULE_START_DATE,
      SCHEDULE_END_DATE,
      0 AS MONDAY,
      0 AS TUESDAY,
      0 AS WEDNESDAY,
      0 AS THURSDAY,
      0 AS FRIDAY,
      0 AS SATURDAY,
      1 AS SUNDAY,
      SUNDAY_TIME AS TALK_TIME,
