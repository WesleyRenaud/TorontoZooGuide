      SCHEDULE_MESSAGE
   FROM GuardiansTalkSchedule
   WHERE TUESDAY_TIME IS NOT NULL
      AND TRIM( TUESDAY_TIME ) != ''

   UNION ALL

   SELECT
      TALK_NAME,
      LOCATION,
      SCHEDULE_START_DATE,
      SCHEDULE_END_DATE,
