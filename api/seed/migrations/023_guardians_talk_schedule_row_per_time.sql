DROP TABLE IF EXISTS GuardiansTalkScheduleMigration;

CREATE TABLE GuardiansTalkScheduleMigration
(  TALK_NAME              VARCHAR(64) NOT NULL,
   LOCATION               VARCHAR(64) NOT NULL,
   SCHEDULE_START_DATE    DATE        NOT NULL,
   SCHEDULE_END_DATE      DATE,
   MONDAY                 BOOL        NOT NULL DEFAULT 0,
   TUESDAY                BOOL        NOT NULL DEFAULT 0,
   WEDNESDAY              BOOL        NOT NULL DEFAULT 0,
   THURSDAY               BOOL        NOT NULL DEFAULT 0,
   FRIDAY                 BOOL        NOT NULL DEFAULT 0,
   SATURDAY               BOOL        NOT NULL DEFAULT 0,
   SUNDAY                 BOOL        NOT NULL DEFAULT 0,
   TALK_TIME              TEXT        NOT NULL,
   SCHEDULE_MESSAGE       TEXT,
   PRIMARY KEY (TALK_NAME, LOCATION, TALK_TIME, SCHEDULE_START_DATE),
   FOREIGN KEY (TALK_NAME, LOCATION) REFERENCES MeetTheGuardiansTalk(NAME, LOCATION) );

INSERT OR IGNORE INTO GuardiansTalkScheduleMigration (
   TALK_NAME,
   LOCATION,
   SCHEDULE_START_DATE,
   SCHEDULE_END_DATE,
   MONDAY,
   TUESDAY,
   WEDNESDAY,
   THURSDAY,
   FRIDAY,
   SATURDAY,
   SUNDAY,
   TALK_TIME,
   SCHEDULE_MESSAGE
)
SELECT
   TALK_NAME,
   LOCATION,
   SCHEDULE_START_DATE,
   MAX( SCHEDULE_END_DATE ),
   MAX( MONDAY ),
   MAX( TUESDAY ),
   MAX( WEDNESDAY ),
   MAX( THURSDAY ),
   MAX( FRIDAY ),
   MAX( SATURDAY ),
   MAX( SUNDAY ),
   TALK_TIME,
   MAX( SCHEDULE_MESSAGE )
FROM (
   SELECT
      TALK_NAME,
      LOCATION,
      SCHEDULE_START_DATE,
      SCHEDULE_END_DATE,
      1 AS MONDAY,
      0 AS TUESDAY,
      0 AS WEDNESDAY,
      0 AS THURSDAY,
      0 AS FRIDAY,
      0 AS SATURDAY,
      0 AS SUNDAY,
      MONDAY_TIME AS TALK_TIME,
      SCHEDULE_MESSAGE
   FROM GuardiansTalkSchedule
   WHERE MONDAY_TIME IS NOT NULL
      AND TRIM( MONDAY_TIME ) != ''

   UNION ALL

   SELECT
      TALK_NAME,
      LOCATION,
      SCHEDULE_START_DATE,
      SCHEDULE_END_DATE,
      0 AS MONDAY,
      1 AS TUESDAY,
      0 AS WEDNESDAY,
      0 AS THURSDAY,
      0 AS FRIDAY,
      0 AS SATURDAY,
      0 AS SUNDAY,
